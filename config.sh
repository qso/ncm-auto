#!/bin/bash
# ===== ncm-auto 配置 =====
# 修改后无需重装，下一次扫描（约 20 秒内）自动生效。

# 网易云音乐的下载目录（可写多个，用空格分隔，递归扫描子目录）
WATCH_DIRS=("$HOME/Music/网易云音乐")

# 解密后的音乐输出目录（会保留下载目录里的子文件夹结构）
OUTPUT_DIR="$HOME/Music/网易云音乐/已转换"

# 下载的是「无损」(FLAC) 时，额外生成一个 320kbps 的 MP3 副本：
#   1 = 生成（保留 FLAC，同时得到最高音质 MP3）
#   0 = 只保留原始格式（FLAC 就是 FLAC）
MAKE_MP3_COPY=1

# 文件最后修改后至少等待多少秒才转换，避免读到下载到一半的文件
MIN_AGE_SECONDS=10

# 转换成功后弹 macOS 通知：1 = 开，0 = 关
NOTIFY=1
